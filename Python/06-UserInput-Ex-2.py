# Area Calculation

length = float(input("Enter the length of the rectangle: "))
width = float(input("Enter an width of a rectangle:"))
height = float(input("Enter an height of a rectangle:"))

area = length + width
volume = length + width + height

print(f"The area of rectangle is: {area} cm²")
print(f"The Volume of rectangle is: {volume} cm²")












































